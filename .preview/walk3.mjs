import {chromium} from 'playwright-core';
const ctx=await chromium.launchPersistentContext('/dsh-home/.cache/creative-studio-browser-profile',{headless:true,locale:'zh-CN',viewport:{width:1440,height:1100}});
const page=ctx.pages()[0]??await ctx.newPage();
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
await page.goto('http://192.168.31.188:3080/',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForTimeout(2000);
await page.getByRole('button',{name:'创意工坊'}).first().click();
await page.waitForTimeout(1200);
await page.screenshot({path:'.preview/review/zh2-01-chooser.png'});
await page.getByRole('button',{name:/考研市场中台/}).first().click();
await page.waitForTimeout(1500);
await page.screenshot({path:'.preview/review/zh2-02-idea.png'});
const ph=await page.locator('textarea').first().getAttribute('placeholder');
const settings=page.locator('details.cs-advanced').first();
await settings.locator('summary').first().click().catch(()=>{});
await page.waitForTimeout(400);
await page.screenshot({path:'.preview/review/zh2-03-settings.png'});
const effort=await page.locator('select').nth(2).locator('option').first().innerText().catch(()=>'');
const status=await page.locator('.cs-job-status').innerText().catch(()=>'');
const menu=await page.locator('.cs-project-menu summary').first().innerText().catch(()=>'');
const head=await page.locator('.cs-project-head').innerText().catch(()=>'');
console.log(JSON.stringify({ph:ph?.slice(0,40),effort,status,menu,head:head.replace(/\n/g,' | ').slice(0,120),errs}));
