import { chromium } from 'playwright';
const ctx = await chromium.launchPersistentContext('/dsh-home/.cache/creative-studio-browser-profile', { headless: true, executablePath: '/dsh-home/.cache/ms-playwright/chromium-1254/chrome-linux64/chrome', viewport: { width: 1440, height: 950 } });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', error => errs.push(String(error).slice(0, 160)));
page.on('dialog', dialog => dialog.accept());
await page.goto('http://192.168.31.188:3080/', { waitUntil: 'domcontentloaded' });
await page.getByRole('button', { name: 'Creative Studio' }).click({ timeout: 60000 });
await page.waitForTimeout(1400);
const cards = await page.locator('.cs-project-card').allTextContents();
const index = cards.findIndex(text => text.includes('考研市场中台开发'));
await page.locator('.cs-project-card').nth(index).click();
await page.waitForTimeout(1600);
await page.locator('.cs-steps button').first().click();
await page.waitForTimeout(600);
const panel = page.locator('.cs-attachments');
const before = await panel.count();
await page.locator('.cs-attachments input[type=file]').setInputFiles({ name: '需求草稿.md', mimeType: 'text/markdown', buffer: Buffer.from('# 需求\n- 批量导出', 'utf8') });
await page.waitForTimeout(2500);
const alert = await page.locator('.cs-attachments [role=alert]').first().innerText().catch(() => null);
const items = await page.locator('.cs-attachment-list li').count();
console.log(JSON.stringify({ panel: before, error: alert, items, errs }));
await ctx.close();
