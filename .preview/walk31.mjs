import {chromium} from 'playwright-core';
const ctx=await chromium.launchPersistentContext('/dsh-home/.cache/creative-studio-browser-profile',{headless:true,locale:'zh-CN',viewport:{width:1440,height:1300}});
const page=ctx.pages()[0]??await ctx.newPage();
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
await page.goto('http://192.168.31.188:3080/',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForTimeout(1800);
await page.getByRole('button',{name:'创意工坊'}).first().click();
await page.waitForTimeout(900);
await page.getByRole('button',{name:/考研市场中台/}).first().click();
await page.waitForTimeout(1600);
await page.locator('.cs-steps button').nth(1).click();
await page.waitForTimeout(900);
const btn=page.getByRole('button',{name:'重新播放演示'});
const has=await btn.count();
const before=await page.evaluate(()=>{const f=document.querySelectorAll('iframe')[0];if(!f)return 'noiframe';f.dataset.mark='x';return f.dataset.mark;});
await btn.first().click();
await page.waitForTimeout(700);
const after=await page.evaluate(()=>{const f=document.querySelectorAll('iframe')[0];return f?(f.dataset.mark??'remounted'):'noiframe';});
await page.screenshot({path:'.preview/review/zh27-demo-replay.png'});
console.log(JSON.stringify({has,before,after,errs}));
await ctx.close();
