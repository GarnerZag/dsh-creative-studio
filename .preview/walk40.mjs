import {chromium} from 'playwright-core';
const ctx=await chromium.launchPersistentContext('/dsh-home/.cache/creative-studio-browser-profile',{headless:true,locale:'zh-CN',viewport:{width:1440,height:1200}});
const page=ctx.pages()[0]??await ctx.newPage();
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
await page.goto('http://192.168.31.188:3080/',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForTimeout(1600);
await page.getByRole('button',{name:'创意工坊'}).first().click();
await page.waitForTimeout(900);
await page.getByRole('button',{name:/考研市场中台/}).first().click();
await page.waitForTimeout(1600);
const pending=await page.getByText('个问题需要你回答').count();
const text=pending?await page.getByText('个问题需要你回答').first().innerText():'';
const rawKeys=await page.locator('body').innerText().then(t=>/briefPending|chooserNext|detailsDirty|ideaRequired|renameDirty/.test(t));
await page.screenshot({path:'.preview/review/zh34-brief-pending.png'});
console.log(JSON.stringify({pending,text,rawKeys,errs}));
await ctx.close();
