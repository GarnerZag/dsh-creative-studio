import {chromium} from 'playwright-core';
const ctx=await chromium.launchPersistentContext('/dsh-home/.cache/creative-studio-browser-profile',{headless:true,locale:'zh-CN',viewport:{width:1440,height:1100}});
const page=ctx.pages()[0]??await ctx.newPage();
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
await page.goto('http://192.168.31.188:3080/',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForTimeout(1800);
await page.getByRole('button',{name:'创意工坊'}).first().click();
await page.waitForTimeout(900);
await page.getByRole('button',{name:/考研市场中台/}).first().click();
await page.waitForTimeout(1400);
await page.locator('.cs-steps button').nth(2).click();
await page.waitForTimeout(900);
const card=page.locator('svg foreignObject button').first();
await card.click({force:true}).catch(()=>{});
await page.waitForTimeout(600);
const opac=await page.locator('svg path[marker-end]').evaluateAll(ps=>ps.slice(0,8).map(p=>p.getAttribute('opacity')));
await page.screenshot({path:'.preview/review/zh11-arch-selected.png'});
console.log(JSON.stringify({edges:opac,errs}));
